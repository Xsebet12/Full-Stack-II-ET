-------------------------------------------------------------------------------
-- DDL: Regiones y Comunas (Chile)
-------------------------------------------------------------------------------
CREATE TABLE region (
  id_region     NUMBER(10)     PRIMARY KEY,
  nom_region    VARCHAR2(100)  NOT NULL
);

CREATE TABLE comuna (
  id_comuna     NUMBER(10)     PRIMARY KEY,
  nom_comuna    VARCHAR2(100)  NOT NULL,
  id_region     NUMBER(10)     NOT NULL,
  CONSTRAINT fk_comuna_region FOREIGN KEY (id_region) REFERENCES region(id_region)
);

-------------------------------------------------------------------------------
-- DDL: Catálogo
-------------------------------------------------------------------------------
CREATE TABLE categorias (
  id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre    VARCHAR2(100) NOT NULL UNIQUE
);

CREATE TABLE providers (
  id             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_name   VARCHAR2(150) NOT NULL,
  service_type   VARCHAR2(100) NOT NULL,
  url            VARCHAR2(255),
  phone          VARCHAR2(50),
  logo_url       VARCHAR2(255),
  estado         VARCHAR2(20)  NOT NULL
);

CREATE TABLE provider_contacts (
  id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name         VARCHAR2(100) NOT NULL,
  phone        VARCHAR2(50)  NOT NULL,
  role         VARCHAR2(80)  NOT NULL,
  email        VARCHAR2(150) NOT NULL,
  provider_id  NUMBER        NOT NULL,
  principal    NUMBER(1)     DEFAULT 0,
  CONSTRAINT fk_contact_provider FOREIGN KEY (provider_id) REFERENCES providers(id),
  CONSTRAINT ck_contact_principal CHECK (principal IN (0,1))
);

CREATE TABLE productos (
  id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre        VARCHAR2(150)   NOT NULL,
  descripcion   VARCHAR2(1000),
  precio        NUMBER(19,2),
  stock         NUMBER(10),
  imagen        VARCHAR2(255),
  categoria_id  NUMBER          NOT NULL,
  provider_id   NUMBER,
  habilitado    NUMBER(1)       DEFAULT 1 NOT NULL,
  CONSTRAINT fk_prod_categoria FOREIGN KEY (categoria_id) REFERENCES categorias(id),
  CONSTRAINT fk_prod_provider  FOREIGN KEY (provider_id)  REFERENCES providers(id),
  CONSTRAINT ck_prod_habilitado CHECK (habilitado IN (0,1))
);

CREATE TABLE imagenes_producto (
  id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  url          VARCHAR2(255),
  producto_id  NUMBER,
  CONSTRAINT fk_img_producto FOREIGN KEY (producto_id) REFERENCES productos(id)
);

-------------------------------------------------------------------------------
-- DDL: Usuarios
-------------------------------------------------------------------------------
CREATE TABLE usuarios (
  id                 NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombres            VARCHAR2(100) NOT NULL,
  apellidos          VARCHAR2(100) NOT NULL,
  rut                VARCHAR2(12)  NOT NULL UNIQUE,
  dv                 CHAR(1)       NOT NULL,
  correo_electronico VARCHAR2(150) NOT NULL UNIQUE,
  rol                VARCHAR2(20)  NOT NULL,
  contrasena         VARCHAR2(100) NOT NULL,
  direccion          VARCHAR2(255) NOT NULL,
  habilitado         NUMBER(1)     DEFAULT 1 NOT NULL,
  creado_en          TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  id_comuna          NUMBER        NOT NULL,
  CONSTRAINT fk_usu_comuna FOREIGN KEY (id_comuna) REFERENCES comuna(id_comuna),
  CONSTRAINT ck_usu_habilitado CHECK (habilitado IN (0,1))
);

