CREATE TABLE ventas (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id NUMBER NOT NULL,
  fecha TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  total NUMBER(19,2) NOT NULL,
  metodo_pago VARCHAR2(30),
  canal VARCHAR2(30),
  estado_pago VARCHAR2(30),
  CONSTRAINT fk_ventas_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios(id)
);

CREATE TABLE detalle_venta (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venta_id NUMBER NOT NULL,
  producto_id NUMBER NOT NULL,
  cantidad NUMBER(10) NOT NULL,
  precio_unitario NUMBER(19,2) NOT NULL,
  subtotal NUMBER(19,2) NOT NULL,
  CONSTRAINT fk_det_venta_venta FOREIGN KEY (venta_id) REFERENCES ventas(id),
  CONSTRAINT fk_det_venta_producto FOREIGN KEY (producto_id) REFERENCES productos(id)
);

CREATE TABLE boletas (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero NUMBER(20) NOT NULL UNIQUE,
  venta_id NUMBER NOT NULL UNIQUE,
  fecha TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  monto_neto NUMBER(19,2) NOT NULL,
  monto_iva NUMBER(19,2) NOT NULL,
  monto_total NUMBER(19,2) NOT NULL,
  CONSTRAINT fk_boleta_venta FOREIGN KEY (venta_id) REFERENCES ventas(id)
);

CREATE TABLE seguimiento_pedido (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
