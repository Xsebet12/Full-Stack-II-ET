  venta_id NUMBER NOT NULL,
  estado_envio VARCHAR2(30),
  numero_seguimiento VARCHAR2(64),
  fecha_estimada_entrega DATE,
  CONSTRAINT fk_seg_venta FOREIGN KEY (venta_id) REFERENCES ventas(id)
);

